import { contextCheck } from "./context-check";
export type ObservationHint = { topic: string; question: string };

// 작성 주체나 발달 상태를 판정하지 않는, 보완 질문용 규칙입니다.
export function checkObservation(value: string, context = "관찰"): ObservationHint[] {
  const text = value.trim();
  if (!text) return [];
  const contextHints = contextCheck(text, context);
  const hints: ObservationHint[] = [...(contextHints || [])];
  const add = (topic: string, question: string) => hints.push({ topic, question });
  const action = /응시|미소|만지|만졌|잡|놓|쌓|넣|꺼내|가리|바라|살펴|두드|굴리|걸|걷|뛰|움직|웃|울|찡그|끄덕|흔들|밀|당기|말했|말하|말함|먹|마셨|손을|고개를|[“「"].+?[”」"]/.test(text);
  const planning = /지원|계획|연계/.test(context);
  if (!planning && /설명|이야기|스토리|의견을 조율/.test(text) && !/[“「"][^”」"]+[”」"]|라고|라며/.test(text)) add("아이의 실제 발화", "아이가 설명한 말 중 기억나는 표현 하나가 있나요? ‘설명을 잘했다’ 대신 직접 들은 말을 덧붙이면 놀이에 담긴 생각이 더 잘 보여요. 정확히 기억나지 않으면 인용문을 만들지 않아도 돼요.");
  if (/기억력이? 좋|기억력이? 뛰|초롱초롱|탄탄한|스토리가? (?:꽤 )?탄탄/.test(text)) add("관찰과 해석", "그렇게 느끼게 한 말이나 장면이 있나요? 예를 들어 이전 경험을 떠올렸다면 아이가 그 경험을 언급했는지 살펴봐 주세요. 직접 확인한 내용은 관찰에, 선생님의 생각은 해석에 남겨 주세요.");
  if (text.replace(/\s/g, "").length < 20 && !action) add("짧은 기록", "무엇을 대상으로 어떤 행동을 했는지, 기억나는 한 장면을 덧붙여 주세요. 길이만 늘릴 필요는 없어요.");
  if (!action && !planning) add("주요 관찰 장면", "실제로 본 행동이나 들은 말이 있나요? 평가나 해석을 뒷받침하는 장면을 적어 주세요.");
  if (/흥미|관심|좋아|몰입|집중/.test(text) && !action) add("흥미", "어떤 대상을 다시 선택하거나 살펴보았나요? 흥미를 느꼈다고 판단한 행동을 적어 주세요.");
  if (/요구|원했|원하|필요|도움/.test(text) && !/[“"].+?[”"]|가리|내밀|요청|달라고/.test(text)) add("요구", "무엇을 원한다는 것을 어떤 말이나 몸짓으로 표현했나요? 교사가 추측한 요구와 구분해 주세요.");
  if (/발달|수준|능력|미숙|뒤처|또래보다/.test(text)) add("발달 수준", "혼자 해 본 부분과 도움이 필요했던 부분은 무엇인가요? 연령이나 또래 비교만으로 발달 수준을 단정하지 말고 실제 수행을 적어 주세요.");
  if (/성격|특성|소극|적극|예민|산만|항상|원래/.test(text)) add("개별 아동 특성", "이 아이가 이번 장면에서 보인 선택이나 반응은 무엇인가요? 한 장면을 고정된 성격으로 일반화하지 않도록 살펴봐 주세요.");
  if (/학급|반 전체|아이들|모두|분위기/.test(text) && /즐거|활발|산만|차분|어수선|좋/.test(text)) add("학급의 분위기", "분위기를 보여 준 구체적인 장면이 있나요? 여러 아이의 행동과 개별 아이의 반응을 구분해 적어 주세요.");
  if (/기분|감정|즐거|행복|속상|불안|촉감|태도|표정/.test(text) && !/웃|울|찡그|미소|고개|몸을|손을|입꼬리|눈을/.test(text)) add("비언어적 표현", "그때 보인 표정, 시선, 몸의 움직임은 어땠나요? 감정이나 느낌을 단정하기보다 직접 본 반응을 적어 주세요.");
  if (/전인적|유의미|역량|촉진|증진|발달을 도모|감각적 탐색|성취감|오감/.test(text) && !action) add("추상적인 표현", "정리된 교육 용어보다 선생님이 직접 본 장면을 덧붙여 주세요. 이 안내는 AI 작성 여부를 판별한 결과가 아닙니다.");
  if (context === "시간 지원" && !/시간|기다|오래|일과|분|이어/.test(text)) add("지원 유형", "시간을 더 주거나 일과를 조정한 내용인가요? 자료를 제공한 내용이라면 ‘자료 지원’에 해당하는지 확인해 주세요.");
  return hints;
}
